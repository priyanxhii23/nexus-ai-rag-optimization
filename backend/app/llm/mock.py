"""MOCK provider - deterministic, free, and always labelled.

It does NOT generate language. It builds an *extractive* answer by quoting the
retrieved sentences that share the most words with the question, so the RAG,
cache, routing, cost and benchmark logic can be exercised end-to-end without
API keys. Every answer starts with a banner so it can never be mistaken for
real LLM output.
"""
from __future__ import annotations

import re
import time
from collections.abc import Generator

from app.llm.base import LLMProvider, LLMRequest, LLMUsage, estimate_tokens

MOCK_BANNER = "[MOCK RESPONSE - extractive test mode, not generated by an LLM]"
_STOP = set("a an the of to in on for and or is are was were be by with what which who how why when where "
            "does do did can could should would this that these those it its from as at about into than then "
            "please explain describe tell me give list".split())


def _words(t: str) -> set[str]:
    return {w for w in re.findall(r"[a-z0-9]+", t.lower()) if w not in _STOP and len(w) > 1}


class MockProvider(LLMProvider):
    name = "mock"
    is_mock = True

    def __init__(self, delay_s: float = 0.0):
        self.delay_s = delay_s

    def _answer(self, req: LLMRequest) -> str:
        q = _words(req.user.split("QUESTION:")[-1])
        scored: list[tuple[float, int, str]] = []
        for c in req.mock_context:
            for sent in re.split(r"(?<=[.!?])\s+", c.get("text", "")):
                s = sent.strip()
                if 20 <= len(s) <= 500:
                    overlap = len(q & _words(s))
                    if overlap:
                        scored.append((overlap / (len(q) or 1), -int(c["index"]), f"{s} [{c['index']}]"))
        if not scored:
            return (f"{MOCK_BANNER}\n\nThe uploaded documents do not appear to contain information "
                    "that answers this question.")
        scored.sort(reverse=True)
        picked = [s for *_, s in scored[:3]]
        large = "large" in req.model
        lead = "Detailed extract" if large else "Extract"
        return f"{MOCK_BANNER}\n\n{lead} from the retrieved passages:\n\n" + "\n".join(f"- {p}" for p in picked)

    def stream(self, req: LLMRequest) -> Generator[str, None, LLMUsage]:
        text = self._answer(req)
        for i in range(0, len(text), 24):
            if self.delay_s:
                time.sleep(self.delay_s)
            yield text[i:i + 24]
        return LLMUsage(estimate_tokens(req.system + req.user), estimate_tokens(text), "mock", req.model, "end_turn")

    def list_models(self) -> list[str]:
        return ["mock-small", "mock-large"]
